        private const val PKCS12_KEYSTORE_TYPE = "PKCS12"
        private const val CERT_VALIDITY_MILLIS = 10L * 365L * 24L * 60L * 60L * 1000L
        private val JSON_MEDIA_TYPE = "application/json; charset=utf-8".toMediaType()

        fun normalizeFingerprint(fp: String): String =
            fp.trim()
                .lowercase()
                .removePrefix("sha256:")
                .replace(":", "")

        fun certFingerprintSha256(cert: X509Certificate): String {
            val digest = MessageDigest.getInstance("SHA-256").digest(cert.encoded)
            return digest.joinToString("") { "%02x".format(it) }
        }

        fun encodeCertificateToPem(cert: X509Certificate): String {
            val base64Body = Base64.getMimeEncoder(64, "\n".toByteArray(Charsets.US_ASCII))
                .encodeToString(cert.encoded)
            return "-----BEGIN CERTIFICATE-----\n$base64Body\n-----END CERTIFICATE-----\n"
        }

        fun defaultDeviceName(): String {
            val manufacturer = runCatching { Build.MANUFACTURER }.getOrNull().orEmpty().trim()
            val model = runCatching { Build.MODEL }.getOrNull().orEmpty().trim()
            val combined = "$manufacturer $model".trim()
            return combined.ifEmpty { "Android LinuxDeck" }
        }

        private fun sanitizeCn(raw: String): String =
            raw.replace(Regex("[,=+<>#;\\\\\"]"), "").trim().ifEmpty { "Android LinuxDeck" }

        private fun isAndroidKeyStoreAvailable(): Boolean =
            runCatching { KeyStore.getInstance(ANDROID_KEYSTORE_TYPE) != null }.getOrDefault(false)

        private fun ensureBouncyCastleRegistered() {
            if (Security.getProvider(BouncyCastleProvider.PROVIDER_NAME) == null) {
                Security.addProvider(BouncyCastleProvider())
            }
        }

        private fun createTls13Context(): SSLContext =
            runCatching { SSLContext.getInstance("TLSv1.3") }
                .getOrElse { SSLContext.getInstance("TLS") }

        private fun ensureSecureDir(dir: File) {
            if (!dir.exists()) {
                dir.mkdirs()
            }
            dir.setReadable(false, false)
            dir.setReadable(true, true)
            dir.setWritable(false, false)
            dir.setWritable(true, true)
            dir.setExecutable(false, false)
            dir.setExecutable(true, true)
        }

        private fun writeRestrictedFile(file: File, bytes: ByteArray) {
            val tmp = File(file.parentFile, "${file.name}.tmp")
            tmp.writeBytes(bytes)
            restrictFilePermissions(tmp)
            if (!tmp.renameTo(file)) {
                file.writeBytes(bytes)
                tmp.delete()
            }
            restrictFilePermissions(file)
        }

        private fun restrictFilePermissions(file: File) {
            file.setReadable(false, false)
            file.setReadable(true, true)
            file.setWritable(false, false)
            file.setWritable(true, true)
        }
    }
