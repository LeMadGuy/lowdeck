/**
 * Plain TCP [SocketFactory] used underneath the TLS 1.3 layer that disables Nagle's algorithm
 * (`TCP_NODELAY`) and enables `SO_KEEPALIVE` on every socket.
 *
 * Without `TCP_NODELAY`, tiny high-frequency WebSocket frames (trackpad `MouseMoveEvent` at 60–120 Hz)
 * are held back by Nagle + delayed-ACK interaction for up to ~40 ms, producing visible cursor stutter,
 * especially over `adb reverse` USB tunnels.
 */
object LowLatencySocketFactory : SocketFactory() {
    private val delegate: SocketFactory = getDefault()

    private fun Socket.tuned(): Socket = apply {
        tcpNoDelay = true
        keepAlive = true
    }

    override fun createSocket(): Socket = delegate.createSocket().tuned()

    override fun createSocket(host: String?, port: Int): Socket =
        delegate.createSocket(host, port).tuned()

    override fun createSocket(host: String?, port: Int, localHost: InetAddress?, localPort: Int): Socket =
        delegate.createSocket(host, port, localHost, localPort).tuned()

    override fun createSocket(host: InetAddress?, port: Int): Socket =
        delegate.createSocket(host, port).tuned()

    override fun createSocket(address: InetAddress?, port: Int, localAddress: InetAddress?, localPort: Int): Socket =
        delegate.createSocket(address, port, localAddress, localPort).tuned()
}

/**
 * Represents the QR Code JSON payload generated by `daemon --pair` in TASK-02.
 */
data class PairingQrPayload(
    val host: String,
    val port: Int = DEFAULT_CONTROL_PORT,
    val pairingPort: Int = DEFAULT_PAIRING_PORT,
    val serverFp: String,
    val token: String,
    val expiresAt: Long = 0L,
) {
    companion object {
        const val DEFAULT_CONTROL_PORT = 8443
        const val DEFAULT_PAIRING_PORT = 8444

        /**
         * Parses either a full QR JSON payload (`{"host":...,"token":...}`) or a raw hex token string.
         */
        fun parse(
            rawInput: String,
            fallbackHost: String = "127.0.0.1",
            fallbackPort: Int = DEFAULT_CONTROL_PORT,
            fallbackPairingPort: Int = DEFAULT_PAIRING_PORT,
            fallbackServerFp: String = "",
        ): PairingQrPayload {
            val trimmed = rawInput.trim()
            require(trimmed.isNotEmpty()) { "O payload ou token de pareamento não pode estar vazio." }

            if (trimmed.startsWith("{")) {
                val json = JSONObject(trimmed)
                val host = json.optString("host", fallbackHost).trim().ifEmpty { fallbackHost }
                val port = json.optInt("port", fallbackPort).takeIf { it in 1..65535 } ?: fallbackPort
                val pairingPort = json.optInt("pairing_port", fallbackPairingPort)
                    .takeIf { it in 1..65535 } ?: fallbackPairingPort
                val serverFp = MtlsKeyManager.normalizeFingerprint(
                    json.optString("server_fp", fallbackServerFp),
                )
                val token = json.optString("token", "").trim()
                val expiresAt = json.optLong("expires_at", 0L)

                require(token.isNotEmpty()) { "Campo 'token' ausente no JSON de pareamento." }

                return PairingQrPayload(
                    host = host,
                    port = port,
                    pairingPort = pairingPort,
                    serverFp = serverFp,
                    token = token,
                    expiresAt = expiresAt,
                )
            }

            return PairingQrPayload(
                host = fallbackHost.trim().ifEmpty { "127.0.0.1" },
                port = fallbackPort,
                pairingPort = fallbackPairingPort,
                serverFp = MtlsKeyManager.normalizeFingerprint(fallbackServerFp),
                token = trimmed,
                expiresAt = 0L,
            )
        }
    }
}

/**
 * Persisted configuration of a paired and pinned Linux Deck host.
 */
data class PairedHostConfig(
    val host: String,
    val port: Int,
    val pairingPort: Int,
    val serverFingerprintSha256: String,
    val deviceId: String,
    val deviceName: String,
    val pairedAtEpochSec: Long,
) {
    fun toJson(): JSONObject = JSONObject().apply {
        put("host", host)
        put("port", port)
        put("pairing_port", pairingPort)
        put("server_fp", serverFingerprintSha256)
        put("device_id", deviceId)
        put("device_name", deviceName)
        put("paired_at", pairedAtEpochSec)
    }

    companion object {
        fun fromJson(json: JSONObject): PairedHostConfig = PairedHostConfig(
            host = json.getString("host"),
            port = json.optInt("port", PairingQrPayload.DEFAULT_CONTROL_PORT),
            pairingPort = json.optInt("pairing_port", PairingQrPayload.DEFAULT_PAIRING_PORT),
            serverFingerprintSha256 = MtlsKeyManager.normalizeFingerprint(json.getString("server_fp")),
            deviceId = json.getString("device_id"),
            deviceName = json.optString("device_name", "Android Deck Client"),
            pairedAtEpochSec = json.optLong("paired_at", 0L),
        )
    }
}

/**
 * Public metadata of the client's ECDSA P-256 X.509 identity.
 */
data class ClientCertificateIdentity(
    val certificate: X509Certificate,
    val certificatePem: String,
    val fingerprintSha256: String,
)

/**
 * Manages the Android client's ECDSA P-256 keypair, X.509 client certificate,
 * SHA-256 server certificate pinning, and mTLS 1.3 OkHttpClient instances.
 *
 * All disk I/O, KeyStore operations, and TLS handshakes run exclusively on [ioDispatcher] (`Dispatchers.IO`).
 */
class MtlsKeyManager(
    private val storageDir: File,
    private val preferAndroidKeyStore: Boolean = isAndroidKeyStoreAvailable(),
    private val ioDispatcher: CoroutineDispatcher = Dispatchers.IO,
) {
    constructor(context: Context) : this(
        storageDir = File(context.applicationContext.filesDir, "security"),
    )

    private val mutex = Mutex()
    private val pairedHostFile = File(storageDir, "paired_host.json")
    private val pkcs12File = File(storageDir, "client_identity.p12")
    private val pkcs12SecretFile = File(storageDir, "client_identity.secret")

    private val _pairedHost = MutableStateFlow<PairedHostConfig?>(loadPairedHostSync())
    val pairedHost: StateFlow<PairedHostConfig?> = _pairedHost.asStateFlow()

    init {
        ensureBouncyCastleRegistered()
    }

    /**
     * Loads or generates the client's ECDSA P-256 keypair and self-signed X.509 certificate.
     */
    suspend fun ensureClientIdentity(
        deviceName: String = defaultDeviceName(),
    ): ClientCertificateIdentity = withContext(ioDispatcher) {
        mutex.withLock {
            val keyStore = loadOrCreateClientKeyStore(deviceName)
            val cert = keyStore.getCertificate(KEY_ALIAS) as? X509Certificate
                ?: throw IllegalStateException("Certificado X.509 do cliente ausente após inicialização.")
            ClientCertificateIdentity(
                certificate = cert,
                certificatePem = encodeCertificateToPem(cert),
                fingerprintSha256 = certFingerprintSha256(cert),
            )
        }
    }

    /**
     * Builds an [OkHttpClient] configured with mutual TLS 1.3 (presenting the client's ECDSA X.509
     * certificate) and strict SHA-256 certificate pinning against the Linux daemon's certificate.
     */
    suspend fun buildPinnedOkHttpClient(
        expectedServerFingerprintSha256: String,
        deviceName: String = defaultDeviceName(),
        connectTimeoutSeconds: Long = 10L,
        pingIntervalSeconds: Long = 0L,
    ): OkHttpClient = withContext(ioDispatcher) {
        val normalizedPin = normalizeFingerprint(expectedServerFingerprintSha256)
        require(normalizedPin.length == 64) {
            "SHA-256 fingerprint do servidor inválido (esperado 64 caracteres hex)."
        }

        val (keyStore, keyPassword) = mutex.withLock {
            val ks = loadOrCreateClientKeyStore(deviceName)
            val pwd = if (ks.type == ANDROID_KEYSTORE_TYPE) null else getOrCreatePkcs12Password()
            ks to pwd
        }

        val kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm())
        kmf.init(keyStore, keyPassword)

        val trustManager = PinnedServerTrustManager(normalizedPin)
        val sslContext = createTls13Context()
        sslContext.init(kmf.keyManagers, arrayOf(trustManager), SecureRandom())

        val tls13Spec = ConnectionSpec.Builder(ConnectionSpec.MODERN_TLS)
            .tlsVersions(TlsVersion.TLS_1_3)
            .build()

        val pinnedHostnameVerifier = HostnameVerifier { _, session ->
            try {
                val peerCert = session.peerCertificates.firstOrNull() as? X509Certificate
                    ?: return@HostnameVerifier false
                val actualFp = certFingerprintSha256(peerCert)
                MessageDigest.isEqual(
                    actualFp.toByteArray(Charsets.US_ASCII),
                    normalizedPin.toByteArray(Charsets.US_ASCII),
                )
            } catch (_: SSLPeerUnverifiedException) {
                false
            }
        }

        OkHttpClient.Builder()
            .socketFactory(LowLatencySocketFactory)
            .sslSocketFactory(sslContext.socketFactory, trustManager)
            .hostnameVerifier(pinnedHostnameVerifier)
            .connectionSpecs(listOf(tls13Spec))
            .connectTimeout(connectTimeoutSeconds, TimeUnit.SECONDS)
            .readTimeout(0L, TimeUnit.MILLISECONDS)
            .apply {
                if (pingIntervalSeconds > 0L) {
                    pingInterval(pingIntervalSeconds, TimeUnit.SECONDS)
                }
            }
            .build()
    }

    /**
     * Executes the one-time pairing handshake (`POST /pair`) against the Linux daemon,
     * validates the server's pinned SHA-256 certificate, and persists [PairedHostConfig].
     */
    suspend fun pairWithDaemon(
        qrPayload: PairingQrPayload,
        deviceId: String? = null,
        deviceName: String = defaultDeviceName(),
    ): PairedHostConfig = withContext(ioDispatcher) {
        if (qrPayload.expiresAt > 0L) {
            val nowSec = System.currentTimeMillis() / 1000L
            if (nowSec >= qrPayload.expiresAt) {
                throw IOException("O token de pareamento expirou. Gere um novo QR Code com 'daemon --pair'.")
            }
        }

        val clientIdentity = ensureClientIdentity(deviceName)
        val resolvedDeviceId = deviceId?.trim()?.takeIf { it.isNotEmpty() }
            ?: getOrCreatePersistentDeviceId(clientIdentity.fingerprintSha256)

        val requestJson = JSONObject().apply {
            put("token", qrPayload.token)
            put("device_id", resolvedDeviceId)
            put("device_name", deviceName)
            put("client_cert_pem", clientIdentity.certificatePem)
        }

        val pairingClient = if (qrPayload.serverFp.isNotEmpty()) {
            buildPinnedOkHttpClient(
                expectedServerFingerprintSha256 = qrPayload.serverFp,
                deviceName = deviceName,
                connectTimeoutSeconds = 5L,
            )
        } else {
            buildBootstrapPairingClient(deviceName)
        }

        val requestBodyStr = requestJson.toString()

        val (effectiveHost, bodyText) = try {
            qrPayload.host to executePairingHttpCall(
                client = pairingClient,
                host = qrPayload.host,
                pairingPort = qrPayload.pairingPort,
                requestBodyJson = requestBodyStr,
            )
        } catch (primaryErr: IOException) {
            val isNetworkUnreachable = primaryErr is ConnectException || primaryErr is SocketTimeoutException
            if (isNetworkUnreachable && qrPayload.host != "127.0.0.1") {
                // Automatic USB `adb reverse` fallback when LAN IP is blocked by host firewall (e.g. UFW)
                try {
                    "127.0.0.1" to executePairingHttpCall(
                        client = pairingClient,
                        host = "127.0.0.1",
                        pairingPort = qrPayload.pairingPort,
                        requestBodyJson = requestBodyStr,
                    )
                } catch (_: IOException) {
                    throw IOException(
                        "Não foi possível conectar a ${qrPayload.host}:${qrPayload.pairingPort} nem via USB (127.0.0.1:${qrPayload.pairingPort}). " +
                            "Verifique se 'deck-daemon --pair' está rodando no Linux e:\n" +
                            "• Via USB: execute 'adb reverse tcp:${qrPayload.port} tcp:${qrPayload.port} && adb reverse tcp:${qrPayload.pairingPort} tcp:${qrPayload.pairingPort}'\n" +
                            "• Via Wi-Fi: libere o firewall com 'sudo ufw allow ${qrPayload.port},${qrPayload.pairingPort}/tcp'",
                        primaryErr,
                    )
                }
            } else if (isNetworkUnreachable && qrPayload.host == "127.0.0.1") {
                throw IOException(
                    "Falha ao conectar via USB em 127.0.0.1:${qrPayload.pairingPort}. " +
                        "Confirme que 'deck-daemon --pair' está rodando no PC e execute:\n" +
                        "adb reverse tcp:${qrPayload.port} tcp:${qrPayload.port} && adb reverse tcp:${qrPayload.pairingPort} tcp:${qrPayload.pairingPort}",
                    primaryErr,
                )
            } else {
                throw primaryErr
            }
        }

        val respJson = JSONObject(bodyText)
        val status = respJson.optString("status", "")
        if (status != "paired") {
            throw IOException("Resposta inesperada do servidor de pareamento: status='$status'")
        }

        val returnedServerFp = normalizeFingerprint(respJson.optString("server_fp", ""))
        if (returnedServerFp.length != 64) {
            throw IOException("Servidor retornou server_fp inválido.")
        }
        if (qrPayload.serverFp.isNotEmpty() && returnedServerFp != qrPayload.serverFp) {
            throw CertificateException(
                "Divergência de fingerprint no pareamento: esperado ${qrPayload.serverFp}, recebido $returnedServerFp",
            )
        }

        val config = PairedHostConfig(
            host = effectiveHost,
            port = qrPayload.port,
            pairingPort = qrPayload.pairingPort,
            serverFingerprintSha256 = returnedServerFp,
            deviceId = respJson.optString("device_id", resolvedDeviceId),
            deviceName = deviceName,
            pairedAtEpochSec = respJson.optLong("paired_at", System.currentTimeMillis() / 1000L),
        )
        savePairedHost(config)
        config
    }

    private fun executePairingHttpCall(
        client: OkHttpClient,
        host: String,
        pairingPort: Int,
        requestBodyJson: String,
    ): String {
        val url = "https://$host:$pairingPort/pair"
        val request = Request.Builder()
            .url(url)
            .post(requestBodyJson.toRequestBody(JSON_MEDIA_TYPE))
            .header("Content-Type", "application/json")
            .build()

        client.newCall(request).execute().use { response ->
            val bodyText = response.body?.string().orEmpty()
            if (!response.isSuccessful) {
                throw IOException("Falha no pareamento (HTTP ${response.code}): ${bodyText.trim()}")
            }
            return bodyText
        }
    }

    /**
     * Updates the host/port of an already paired Linux machine (e.g., switching between LAN mDNS IP
     * and USB `127.0.0.1` via `adb reverse`) while preserving the cryptographic SHA-256 certificate pin.
     */
    suspend fun updateEndpointAddress(host: String, port: Int = PairingQrPayload.DEFAULT_CONTROL_PORT): PairedHostConfig? =
        withContext(ioDispatcher) {
            mutex.withLock {
                val current = _pairedHost.value ?: return@withLock null
                val updated = current.copy(host = host.trim(), port = port)
                writeRestrictedFile(pairedHostFile, updated.toJson().toString(2).toByteArray(Charsets.UTF_8))
                _pairedHost.value = updated
                updated
            }
        }

    suspend fun savePairedHost(config: PairedHostConfig) = withContext(ioDispatcher) {
        mutex.withLock {
            ensureSecureDir(storageDir)
            writeRestrictedFile(pairedHostFile, config.toJson().toString(2).toByteArray(Charsets.UTF_8))
            _pairedHost.value = config
        }
    }

    suspend fun clearPairedHost() = withContext(ioDispatcher) {
        mutex.withLock {
            if (pairedHostFile.exists()) {
                pairedHostFile.delete()
            }
            _pairedHost.value = null
        }
    }

    private fun loadPairedHostSync(): PairedHostConfig? {
        if (!pairedHostFile.exists()) return null
        return runCatching {
            val content = pairedHostFile.readText(Charsets.UTF_8)
            PairedHostConfig.fromJson(JSONObject(content))
        }.getOrNull()
    }

    private fun getOrCreatePersistentDeviceId(clientFp: String): String {
        val idFile = File(storageDir, "device_id.txt")
        if (idFile.exists()) {
            val existing = idFile.readText(Charsets.UTF_8).trim()
            if (existing.isNotEmpty()) return existing
        }
        ensureSecureDir(storageDir)
        val generated = "android-${clientFp.take(12)}-${UUID.randomUUID().toString().take(6)}"
        writeRestrictedFile(idFile, generated.toByteArray(Charsets.UTF_8))
        return generated
    }

    private fun loadOrCreateClientKeyStore(deviceName: String): KeyStore {
        if (preferAndroidKeyStore) {
            val androidKs = runCatching { loadOrCreateAndroidKeyStore(deviceName) }.getOrNull()
            if (androidKs != null) {
                return androidKs
            }
        }
        return loadOrCreatePkcs12KeyStore(deviceName)
    }

    private fun loadOrCreateAndroidKeyStore(deviceName: String): KeyStore {
        val ks = KeyStore.getInstance(ANDROID_KEYSTORE_TYPE).apply { load(null) }
        if (ks.containsAlias(LEGACY_KEY_ALIAS)) {
            runCatching { ks.deleteEntry(LEGACY_KEY_ALIAS) }
        }
        if (!ks.containsAlias(KEY_ALIAS)) {
            val now = Date()
            val notBefore = Date(now.time - 5 * 60 * 1000L)
            val notAfter = Date(now.time + CERT_VALIDITY_MILLIS)
            val kpg = KeyPairGenerator.getInstance(
                KeyProperties.KEY_ALGORITHM_EC,
                ANDROID_KEYSTORE_TYPE,
            )
            val spec = KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_SIGN or KeyProperties.PURPOSE_VERIFY,
            )
                .setAlgorithmParameterSpec(ECGenParameterSpec("secp256r1"))
                // KeyProperties.DIGEST_NONE is mandatory for Android Conscrypt / BoringSSL TLS 1.3
                // client authentication (EcdsaMethodDoSign invokes NONEwithECDSA on pre-hashed transcripts).
                .setDigests(
                    KeyProperties.DIGEST_NONE,
                    KeyProperties.DIGEST_SHA256,
                    KeyProperties.DIGEST_SHA384,
                    KeyProperties.DIGEST_SHA512,
                )
                .setCertificateSubject(X500Principal("CN=${sanitizeCn(deviceName)}, O=LinuxDeck Remote"))
                .setCertificateSerialNumber(BigInteger(128, SecureRandom()).abs().max(BigInteger.ONE))
                .setCertificateNotBefore(notBefore)
                .setCertificateNotAfter(notAfter)
                .build()
            kpg.initialize(spec)
            kpg.generateKeyPair()
        }

        // Verify hardware KeyMint actually permits NONEwithECDSA required by BoringSSL TLS 1.3;
        // if a vendor TEE blocks DIGEST_NONE, loadOrCreateClientKeyStore falls back to PKCS12.
        val privateKey = ks.getKey(KEY_ALIAS, null) as? PrivateKey
            ?: throw IllegalStateException("Chave privada ECDSA ausente no AndroidKeyStore.")
        Signature.getInstance("NONEwithECDSA").apply {
            initSign(privateKey)
            update(ByteArray(32))
            sign()
        }

        return ks
    }

    private fun loadOrCreatePkcs12KeyStore(deviceName: String): KeyStore {
        ensureSecureDir(storageDir)
        val password = getOrCreatePkcs12Password()
        val ks = KeyStore.getInstance(PKCS12_KEYSTORE_TYPE)

        if (pkcs12File.exists()) {
            pkcs12File.inputStream().use { ks.load(it, password) }
            if (ks.containsAlias(KEY_ALIAS)) {
                return ks
            }
        } else {
            ks.load(null, password)
        }

        val kpg = KeyPairGenerator.getInstance("EC")
        kpg.initialize(ECGenParameterSpec("secp256r1"), SecureRandom())
        val keyPair = kpg.generateKeyPair()

        val now = System.currentTimeMillis()
        val notBefore = Date(now - 5 * 60 * 1000L)
        val notAfter = Date(now + CERT_VALIDITY_MILLIS)
        val serial = BigInteger(128, SecureRandom()).abs().max(BigInteger.ONE)
        val subject = X500Name("CN=${sanitizeCn(deviceName)},O=LinuxDeck Remote")

        val certBuilder = JcaX509v3CertificateBuilder(
            subject,
            serial,
            notBefore,
            notAfter,
            subject,
            keyPair.public,
        )
        certBuilder.addExtension(
            Extension.keyUsage,
            true,
            KeyUsage(KeyUsage.digitalSignature or KeyUsage.keyEncipherment),
        )
        certBuilder.addExtension(
            Extension.extendedKeyUsage,
            false,
            ExtendedKeyUsage(KeyPurposeId.id_kp_clientAuth),
        )

        val signer = JcaContentSignerBuilder("SHA256withECDSA").build(keyPair.private)
        val certHolder = certBuilder.build(signer)
        val cert = JcaX509CertificateConverter().getCertificate(certHolder)

        ks.setKeyEntry(KEY_ALIAS, keyPair.private, password, arrayOf(cert))

        val tmpFile = File(storageDir, "${pkcs12File.name}.tmp")
        tmpFile.outputStream().use { ks.store(it, password) }
        restrictFilePermissions(tmpFile)
        if (!tmpFile.renameTo(pkcs12File)) {
            writeRestrictedFile(pkcs12File, tmpFile.readBytes())
            tmpFile.delete()
        }
        restrictFilePermissions(pkcs12File)

        return ks
    }

    private fun getOrCreatePkcs12Password(): CharArray {
        ensureSecureDir(storageDir)
        if (pkcs12SecretFile.exists()) {
            val existing = pkcs12SecretFile.readText(Charsets.UTF_8).trim()
            if (existing.isNotEmpty()) return existing.toCharArray()
        }
        val randomBytes = ByteArray(32)
        SecureRandom().nextBytes(randomBytes)
        val hexSecret = randomBytes.joinToString("") { "%02x".format(it) }
        writeRestrictedFile(pkcs12SecretFile, hexSecret.toByteArray(Charsets.UTF_8))
        return hexSecret.toCharArray()
    }

    private suspend fun buildBootstrapPairingClient(deviceName: String): OkHttpClient = withContext(ioDispatcher) {
        val (keyStore, keyPassword) = mutex.withLock {
            val ks = loadOrCreateClientKeyStore(deviceName)
            val pwd = if (ks.type == ANDROID_KEYSTORE_TYPE) null else getOrCreatePkcs12Password()
            ks to pwd
        }
        val kmf = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm())
        kmf.init(keyStore, keyPassword)

        @SuppressLint("CustomX509TrustManager")
        val bootstrapTrust = object : X509ExtendedTrustManager() {
            override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit
            override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?, socket: Socket?) = Unit
            override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?, engine: SSLEngine?) = Unit

            override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) {
                if (chain.isNullOrEmpty()) {
                    throw CertificateException("Servidor não apresentou certificado TLS.")
                }
                chain[0].checkValidity()
            }

            override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?, socket: Socket?) {
                checkServerTrusted(chain, authType)
            }

            override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?, engine: SSLEngine?) {
                checkServerTrusted(chain, authType)
            }

            override fun getAcceptedIssuers(): Array<X509Certificate> = emptyArray()
        }

        val sslContext = createTls13Context()
        sslContext.init(kmf.keyManagers, arrayOf(bootstrapTrust), SecureRandom())
        val tls13Spec = ConnectionSpec.Builder(ConnectionSpec.MODERN_TLS)
            .tlsVersions(TlsVersion.TLS_1_3)
            .build()

        OkHttpClient.Builder()
            .socketFactory(LowLatencySocketFactory)
            .sslSocketFactory(sslContext.socketFactory, bootstrapTrust)
            .hostnameVerifier { _, session -> session.peerCertificates.isNotEmpty() }
            .connectionSpecs(listOf(tls13Spec))
            .connectTimeout(5L, TimeUnit.SECONDS)
            .build()
    }

    @SuppressLint("CustomX509TrustManager")
    private class PinnedServerTrustManager(
        private val expectedSha256Hex: String,
    ) : X509ExtendedTrustManager() {
        override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) {
            throw CertificateException("PinnedServerTrustManager valida apenas certificados de servidor.")
        }

        override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?, socket: Socket?) {
            checkClientTrusted(chain, authType)
        }

        override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?, engine: SSLEngine?) {
            checkClientTrusted(chain, authType)
        }

        override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) {
            if (chain.isNullOrEmpty()) {
                throw CertificateException("Servidor Linux não apresentou certificado X.509.")
            }
            val leaf = chain[0]
            leaf.checkValidity()

            val actualFp = certFingerprintSha256(leaf)
            val matches = MessageDigest.isEqual(
                actualFp.toByteArray(Charsets.US_ASCII),
                expectedSha256Hex.toByteArray(Charsets.US_ASCII),
            )
            if (!matches) {
                throw CertificateException(
                    "Falha no Certificate Pinning SHA-256: esperado=$expectedSha256Hex, recebido=$actualFp",
                )
            }
        }

        override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?, socket: Socket?) {
            checkServerTrusted(chain, authType)
        }

        override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?, engine: SSLEngine?) {
            checkServerTrusted(chain, authType)
        }

        override fun getAcceptedIssuers(): Array<X509Certificate> = emptyArray()
    }

